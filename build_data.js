// Builds data.js from the study guides in c:\dev\docs\GANDALF\ .
// Run: node build_data.js [path-to-GANDALF]
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = process.argv[2] || 'c:\\dev\\docs\\GANDALF';
const HE = /[\u0590-\u05FF]/;
const CHUNK = 40;

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/\r/g, '').split('\n');
}

// Splits a file into { title, lines } using "title" + "====" / "----" underline headers.
function sections(lines) {
  const out = [];
  let cur = null;
  for (let i = 0; i < lines.length; i++) {
    const next = lines[i + 1] || '';
    if (lines[i].trim() && /^[=-]{3,}\s*$/.test(next)) {
      cur = { title: lines[i].trim().replace(/^[\dא-ת]+\.\s*/, ''), lines: [] };
      out.push(cur);
      i++;
      continue;
    }
    if (cur) cur.lines.push(lines[i]);
  }
  return out;
}

const parts = (line) => line.split(' — ').map((s) => s.trim());

// "english — hebrew[. note]" or "english — hebrew — note"
function entries(sec) {
  const words = [];
  for (const line of sec.lines) {
    if (!line.includes(' — ')) continue;
    const p = parts(line);
    if (HE.test(p[0]) || !HE.test(p[1] || '')) continue;
    let he = p[1];
    let note = p.slice(2).join(' — ');
    const dot = he.indexOf('. ');
    if (dot > 0) { note = (he.slice(dot + 2) + ' ' + note).trim(); he = he.slice(0, dot); }
    words.push({ en: p[0], he: he.replace(/\.$/, ''), note: note.replace(/\.$/, '') });
  }
  return words;
}

function chunked(name, words) {
  if (words.length <= CHUNK * 1.25) return [{ name, words }];
  const n = Math.ceil(words.length / CHUNK);
  const size = Math.ceil(words.length / n);
  return Array.from({ length: n }, (_, k) => ({ name: `${name} ${k + 1}`, words: words.slice(k * size, (k + 1) * size) }));
}

function groups(rel, { skip = [], min = 6 } = {}) {
  const out = [];
  for (const sec of sections(read(rel))) {
    if (skip.some((s) => sec.title.includes(s))) continue;
    const words = entries(sec);
    if (words.length >= min) out.push(...chunked(sec.title, words));
  }
  return out;
}

// Irregular verbs: "base — past — v3 — hebrew"
const verbs = [];
for (const sec of sections(read('bagrut-5-yehidot/01-dikduk.txt'))) {
  if (!sec.title.includes('פעלים חריגים')) continue;
  for (const line of sec.lines) {
    const p = parts(line);
    if (p.length === 4 && !HE.test(p[0]) && HE.test(p[3]) && p[0] !== 'בסיס') {
      verbs.push({ base: p[0], past: p[1], v3: p[2], he: p[3] });
    }
  }
}

// Word families: "act — action — active — activity" (all English)
const families = [];
for (const sec of sections(read('bagrut-5-yehidot/04-bniyat-milim.txt'))) {
  if (!sec.title.includes('משפחות')) continue;
  for (const line of sec.lines) {
    const p = parts(line);
    if (p.length >= 2 && !p.some((x) => HE.test(x))) families.push(p);
  }
}

const data = {
  source: 'c:\\dev\\docs\\GANDALF',
  bagrutVocab: groups('bagrut-5-yehidot/02-milim-lefi-nose.txt'),
  linkers: groups('bagrut-5-yehidot/03-kishur-ve-tzerufim.txt', { min: 4 }),
  verbs,
  families,
  baLinguistics: groups('toar-rishon-anglit/02-milim-balshanut.txt'),
  baLiterature: groups('toar-rishon-anglit/03-milim-sifrut-ve-akademya.txt', { skip: ['מילים של מאמר'] }),
  baAcademic: sections(read('toar-rishon-anglit/03-milim-sifrut-ve-akademya.txt'))
    .filter((s) => s.title.includes('מילים של מאמר'))
    .flatMap((s) => chunked('מילים של מאמר', entries(s))),
};

const out = path.join(__dirname, 'data.js');
fs.writeFileSync(out, `'use strict';\n// Generated by build_data.js from ${data.source} – do not edit by hand.\nconst GDATA = ${JSON.stringify(data, null, 1)};\n`, 'utf8');

